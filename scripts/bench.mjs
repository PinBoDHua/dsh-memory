#!/usr/bin/env node
/**
 * 大库性能基准：生成合成数据根（global + 一个工作区），测冷/热读取与常见操作。
 * 用法 Run:
 *   node scripts/bench.mjs --entries=30000 [--dir=C:\Temp\dsh-memory-bench-30k] [--regen] [--force]
 * 默认复用已存在的数据根；--regen 重建。为避免误删用户目录：仅当目录带本脚本 marker
 * 或名为 dsh-memory-bench-* 时才允许 --regen 删除，否则需再显式 --force。
 * 输出 JSON 便于对比迭代。
 */
import fs from 'node:fs'
import path from 'node:path'
import os from 'node:os'
import { fileURLToPath } from 'node:url'
import { createMemoryService } from '../lib/service.js'
import { serializeEntry, workspaceKey, listAll, flushSnapshotIndex, clearEntryCache } from '../lib/store.js'

const BENCH_MARKER = '.bench-root'

/** 重建决策（纯函数，便于单测）：返回 'build' | 'reuse'；危险场景抛错。 */
export function resolveBenchRebuild({ dir, regen = false, force = false }) {
  const exists = fs.existsSync(dir)
  if (!exists) return 'build'
  const marked = fs.existsSync(path.join(dir, BENCH_MARKER)) || /(^|[\\/])dsh-memory-bench-/.test(dir)
  if (regen) {
    if (!marked && !force) {
      throw Object.assign(new Error(`拒绝清空非基准目录（需 --force） / refusing to wipe a non-bench directory without --force: ${dir}`), { code: 'refuse' })
    }
    return 'build'
  }
  if (fs.existsSync(path.join(dir, 'global'))) return 'reuse'
  throw Object.assign(new Error(`目录已存在但不是基准数据根，拒绝触碰 / existing directory is not a bench data root: ${dir}`), { code: 'refuse' })
}

function nowMs() { return Number(process.hrtime.bigint() / 1_000_000n) }

function build(root, total, cwd) {
  fs.rmSync(root, { recursive: true, force: true })
  fs.mkdirSync(root, { recursive: true })
  fs.writeFileSync(path.join(root, BENCH_MARKER), 'generated by scripts/bench.mjs\n', 'utf8')
  const globalDir = path.join(root, 'global')
  const key = workspaceKey(cwd)
  const wsDir = path.join(root, 'workspaces', key)
  fs.mkdirSync(globalDir, { recursive: true })
  fs.mkdirSync(wsDir, { recursive: true })
  const globalCount = Math.min(2000, Math.round(total * 0.07))
  const stamp = new Date().toISOString()
  const t = nowMs()
  for (let i = 0; i < total; i += 1) {
    const global = i < globalCount
    const entry = {
      id: `m-bench-${String(i).padStart(6, '0')}`,
      category: ['fact', 'preference', 'decision'][i % 3],
      scope: global ? 'global' : 'workspace',
      tags: i % 5 === 0 ? ['bench', `t${i % 7}`] : [],
      created: stamp,
      updated: `${stamp.slice(0, -2)}${String(i % 100).padStart(2, '0')}Z`,
      source: 'bench',
      content: `基准条目 ${i}：性能测试内容 payload=${'x'.repeat(120)}`,
    }
    const dir = global ? globalDir : wsDir
    fs.writeFileSync(path.join(dir, `${entry.id}.md`), serializeEntry(entry), 'utf8')
  }
  return { buildMs: nowMs() - t, globalCount, workspaceCount: total - globalCount }
}

function run(argv) {
  const argMap = new Map(argv.map((a) => {
    const i = a.indexOf('=')
    return i === -1 ? [a.replace(/^--/, ''), 'true'] : [a.slice(2, i), a.slice(i + 1)]
  }))
  const total = Math.max(100, Number(argMap.get('entries') || 30000))
  const cwd = 'D:\\proj\\alpha'
  const root = argMap.get('dir') || path.join(os.tmpdir(), `dsh-memory-bench-${total}`)
  const mode = resolveBenchRebuild({ dir: root, regen: argMap.has('regen'), force: argMap.has('force') })
  const service = createMemoryService({ root })
  const buildInfo = mode === 'build' ? build(root, total, cwd) : { reused: true }
  const results = { entries: total, root, build: buildInfo }

  let t = nowMs()
  const cold = listAll(root, cwd)
  results.coldListMs = nowMs() - t
  results.coldEntries = cold.length

  const warm = []
  for (let i = 0; i < 5; i += 1) {
    t = nowMs()
    const list = listAll(root, cwd)
    warm.push(nowMs() - t)
    if (i === 0) results.warmEntries = list.length
  }
  results.warmListMs = warm
  // 模拟宿主重启：清空进程内缓存，仅保留磁盘持久化解析索引，测冷启动。
  const indexEntries = flushSnapshotIndex(root)
  clearEntryCache()
  t = nowMs()
  const indexCold = listAll(root, cwd)
  results.indexEntries = indexEntries
  results.indexColdListMs = nowMs() - t
  results.indexColdEntries = indexCold.length
  t = nowMs()
  service.status()
  results.statusMs = nowMs() - t
  t = nowMs()
  service.export({ scope: 'all' })
  results.exportMs = nowMs() - t
  t = nowMs()
  service.recallPreview({ workspace: cwd })
  results.recallPreviewMs = nowMs() - t
  t = nowMs()
  service.search({ query: '基准条目 99999', scope: 'all', workspace: cwd })
  results.searchMs = nowMs() - t
  const target = cold.find((e) => e.scope === 'workspace')
  if (target) {
    t = nowMs()
    service.forget({ id: target.id })
    results.forgetOneMs = nowMs() - t
  }
  console.log(JSON.stringify(results, null, 2))
}

const isDirect = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))
if (isDirect) {
  try {
    run(process.argv.slice(2))
  } catch (err) {
    console.error(`bench 失败 / bench failed: ${err?.message ?? err}`)
    process.exitCode = 2
  }
}